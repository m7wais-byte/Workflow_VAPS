import assert from "node:assert/strict";
import test from "node:test";

async function render(path = "/") {
  const workerUrl = new URL("../dist/server/index.js", import.meta.url);
  workerUrl.searchParams.set("test", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);
  return worker.fetch(
    new Request("http://localhost" + path, { headers: { accept: "text/html" } }),
    { ASSETS: { fetch: async () => new Response("Not found", { status: 404 }) } },
    { waitUntil() {}, passThroughOnException() {} },
  );
}

test("server-renders the VAPS workspace shell", async () => {
  const response = await render();
  assert.equal(response.status, 200);
  assert.match(response.headers.get("content-type") ?? "", /^text\/html\b/i);
  const html = await response.text();
  assert.match(html, /<title>VAPS \| PVT Lab &amp; Sampling<\/title>/);
  assert.match(html, /Loading local workspace/);
  assert.doesNotMatch(html, /Your site is taking shape|Codex/);
});

test("navigation keeps Sampling Reports inside Sampling", async () => {
  const { readFile } = await import("node:fs/promises");
  const page = await readFile(new URL("../app/page.tsx", import.meta.url), "utf8");
  assert.match(page, /const navItems = \["Dashboard", "Jobs", "Sampling", "PVT Lab", "Inventory", "Settings"\]/);
  assert.match(page, /role="tab"[^>]*>[^]*?Sampling Reports/);
});

